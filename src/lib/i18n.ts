export function translate(locale: Locale, text: string): string {
  const key = text.trim();
  const translated = (locale === "id" ? indonesian[key] : english[key]) ?? key;
  return `${/^\s/.test(text) ? " " : ""}${translated}${/\s$/.test(text) ? " " : ""}`;
}
