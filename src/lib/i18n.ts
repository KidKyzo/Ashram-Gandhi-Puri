export const locales = ["en", "id"] as const;
export type Locale = typeof locales[number];
export const defaultLocale: Locale = "en";
export const isLocale = (value: string): value is Locale => value === "en" || value === "id";

export function localizedPath(locale: Locale, path = "/"): string {
  return `/${locale}${path === "/" ? "" : path}`;
}

export function switchLanguagePath(path: string, locale: Locale): string {
  return localizedPath(locale, path.replace(/^\/(en|id)(?=\/|$)/, "") || "/");
}

export function formatMonth(date: string, locale: Locale): string {
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(date)) return date;
  const [year, month] = date.split("-").map(Number);
  return new Intl.DateTimeFormat(locale === "id" ? "id-ID" : "en-GB", {
    month: "long", year: "numeric", timeZone: "UTC",
  }).format(new Date(Date.UTC(year, month - 1, 1)));
}

